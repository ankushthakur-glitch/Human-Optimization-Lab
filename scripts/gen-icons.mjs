import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const PROJECT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const SCRATCH = path.join(PROJECT, "scripts", ".cache")
fs.mkdirSync(SCRATCH, { recursive: true })

const { resolved } = JSON.parse(fs.readFileSync(`${SCRATCH}/icon-map.json`, "utf8"))

const entries = Object.values(resolved).sort((a, b) =>
  a.exportName.localeCompare(b.exportName)
)

const imports = [...new Set(entries.map((e) => e.hugeicon))].sort()

const file = `// Generated by scripts/gen-icons — do not edit by hand.
// Thin wrappers over Hugeicons so icons are used as plain components.
// Stroke weight is controlled globally by --icon-stroke-width (see app/globals.css),
// so these deliberately do not set a strokeWidth prop.
"use client"

import * as React from "react"
import { HugeiconsIcon } from "@hugeicons/react"
import {
${imports.map((i) => `  ${i},`).join("\n")}
} from "@hugeicons/core-free-icons"

export type IconProps = Omit<
  React.ComponentProps<typeof HugeiconsIcon>,
  "icon" | "altIcon"
>

function createIcon(icon: React.ComponentProps<typeof HugeiconsIcon>["icon"]) {
  function Icon(props: IconProps) {
    return <HugeiconsIcon icon={icon} data-icon="" {...props} />
  }
  return Icon
}

${entries.map((e) => `export const ${e.exportName} = createIcon(${e.hugeicon})`).join("\n")}

/** Every icon exposed through this module, for the icon browser. */
export const ICON_CATALOG: { name: string; source: string; Icon: (props: IconProps) => React.ReactElement }[] = [
${entries
  .map((e) => `  { name: "${e.exportName}", source: "${e.hugeicon}", Icon: ${e.exportName} },`)
  .join("\n")}
]
`

fs.writeFileSync(`${PROJECT}/src/design-system/icons.tsx`, file)
console.error(`wrote src/design-system/icons.tsx with ${entries.length} icons`)

// Rewrite my own files off @remixicon/react.
const TARGETS = [
  "src/app/(design-system)/page.tsx",
  "src/app/(design-system)/components/[slug]/page.tsx",
  "src/app/(design-system)/patterns/navigation/page.tsx",
  "src/app/(design-system)/patterns/data/page.tsx",
  "src/app/(design-system)/layouts/page.tsx",
  "src/components/ds-shell.tsx",
  "src/design-system/theme-customizer.tsx",
]

const rename = Object.fromEntries(
  Object.entries(resolved).map(([remix, v]) => [remix, v.exportName])
)

for (const rel of TARGETS) {
  const path = `${PROJECT}/${rel}`
  let src = fs.readFileSync(path, "utf8")

  // Longest names first so e.g. RiArrowDownSLine is not clipped by a shorter prefix.
  for (const remix of Object.keys(rename).sort((a, b) => b.length - a.length)) {
    src = src.replaceAll(new RegExp(`\\b${remix}\\b`, "g"), rename[remix])
  }
  src = src.replaceAll('from "@remixicon/react"', 'from "@/components/icons"')

  fs.writeFileSync(path, src)
  console.error(`rewrote ${rel}`)
}
