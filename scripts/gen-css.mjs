import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const PROJECT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const SCRATCH = path.join(PROJECT, "scripts", ".cache")
fs.mkdirSync(SCRATCH, { recursive: true })

const data = JSON.parse(fs.readFileSync(`${SCRATCH}/themes-all.json`, "utf8"))

const block = (selector, vars) => {
  const body = Object.entries(vars)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join("\n")
  return `${selector} {\n${body}\n}`
}

const out = ["/* Generated by scripts/gen-themes — do not edit by hand. */", ""]

// --radius is owned by the radius selector, not the base palette.
const stripRadius = (vars) =>
  Object.fromEntries(Object.entries(vars).filter(([k]) => k !== "--radius"))

out.push("/* ---------- Base palettes (neutrals, surfaces, borders) ---------- */", "")
for (const [name, v] of Object.entries(data.bases)) {
  out.push(block(`:root[data-base="${name}"]`, stripRadius(v.light)))
  out.push(block(`:root[data-base="${name}"].dark`, stripRadius(v.dark)))
  out.push("")
}

out.push("/* ---------- Accent themes (primary, accent, charts) ---------- */", "")
for (const [name, v] of Object.entries(data.themes)) {
  out.push(block(`:root[data-accent="${name}"]`, v.light))
  out.push(block(`:root[data-accent="${name}"].dark`, v.dark))
  out.push("")
}

out.push("/* ---------- Radius scale ---------- */", "")
for (const [name, v] of Object.entries(data.radii)) {
  out.push(block(`:root[data-radius="${name}"]`, { "--radius": v }))
}
out.push("")

fs.writeFileSync(`${PROJECT}/src/app/themes.css`, out.join("\n"))

// Metadata for the customizer UI.
const accents = Object.entries(data.themes).map(([name, v]) => ({
  name,
  label: name[0].toUpperCase() + name.slice(1),
  swatch: v.light["--primary"],
}))
const bases = Object.entries(data.bases).map(([name, v]) => ({
  name,
  label: name[0].toUpperCase() + name.slice(1),
  swatch: v.light["--muted-foreground"] ?? v.light["--foreground"],
}))
const radii = Object.entries(data.radii).map(([name, v]) => ({ name, value: v }))

const ts = `// Generated by scripts/gen-themes — do not edit by hand.

export type AccentTheme = { name: string; label: string; swatch: string }
export type BasePalette = { name: string; label: string; swatch: string }
export type RadiusOption = { name: string; value: string }

export const ACCENT_THEMES: AccentTheme[] = ${JSON.stringify(accents, null, 2)}

export const BASE_PALETTES: BasePalette[] = ${JSON.stringify(bases, null, 2)}

export const RADIUS_OPTIONS: RadiusOption[] = ${JSON.stringify(radii, null, 2)}
`
fs.writeFileSync(`${PROJECT}/src/design-system/tokens/themes.ts`, ts)

console.error(
  `wrote app/themes.css (${out.join("\n").split("\n").length} lines), lib/themes.ts — ${accents.length} accents, ${bases.length} bases, ${radii.length} radii`
)
